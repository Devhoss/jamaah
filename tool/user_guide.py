# Writes docs/user-guide/in-flight-mode.md from the app's own strings, so the
# guide and the in-app "How it works" page never say different things.
#
#   python tool/user_guide.py
import json
from pathlib import Path

SECTIONS = [
    ('inFlightHelpStartTitle', 'inFlightHelpStartBody'),
    ('inFlightHelpTimesTitle', 'inFlightHelpTimesBody'),
    ('inFlightHelpRouteTitle', 'inFlightHelpRouteBody'),
    ('inFlightHelpQiblaTitle', 'inFlightHelpQiblaBody'),
    ('inFlightHelpAlertsTitle', 'inFlightHelpAlertsBody'),
    ('inFlightHelpTipsTitle', 'inFlightHelpTipsBody'),
]


def section(strings, rtl):
    lines = []
    if rtl:
        lines.append('<div dir="rtl">')
        lines.append('')
    lines += [f"## {strings['inFlightHelpTitle']}", '', strings['inFlightHelpIntro'], '']
    for title, body in SECTIONS:
        lines += [f'### {strings[title]}', '', strings[body], '']
    if rtl:
        lines.append('</div>')
        lines.append('')
    return lines


def main():
    en = json.loads(Path('lib/src/app/l10n/app_en.arb').read_text(encoding='utf-8'))
    ar = json.loads(Path('lib/src/app/l10n/app_ar.arb').read_text(encoding='utf-8'))
    lines = [
        '# In-flight mode — user guide',
        '',
        'Generated by `tool/user_guide.py` from the app\'s strings (the same text as',
        'the in-app “How it works” page, under the ? on the in-flight screen). Edit',
        'the strings, not this file. English first, then Arabic.',
        '',
    ]
    lines += section(en, rtl=False)
    lines += section(ar, rtl=True)
    out = Path('docs/user-guide/in-flight-mode.md')
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'wrote {out}')


if __name__ == '__main__':
    main()
