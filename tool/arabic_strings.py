def plural(var, one, two, few, many, other=None, zero=None):
    """An ICU plural on [var]. Each form is the whole phrase; use {n} for the
    number inside the few/many/other forms."""
    other = other if other is not None else many
    forms = []
    if zero is not None:
        forms.append('=0{%s}' % zero)
    forms += [
        '=1{%s}' % one,
        '=2{%s}' % two,
        'few{%s}' % few.replace('{n}', '{%s}' % var),
        'many{%s}' % many.replace('{n}', '{%s}' % var),
        'other{%s}' % other.replace('{n}', '{%s}' % var),
    ]
    return '{%s, plural, %s}' % (var, ' '.join(forms))


def minutes(var, before='', after=''):
    """'… N minutes …' after a preposition (genitive): دقيقة، دقيقتين،
    ٣ دقائق، ١١ دقيقة."""
    return plural(
        var,
        one=before + 'دقيقة' + after,
        two=before + 'دقيقتين' + after,
        few=before + '{n} دقائق' + after,
        many=before + '{n} دقيقة' + after,
    )


