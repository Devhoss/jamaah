def main():
    en = json.loads(Path('lib/src/app/l10n/app_en.arb').read_text(encoding='utf-8'))
    keys = [k for k in en if not k.startswith('@')]
    missing = [k for k in keys if k not in AR]
    extra = [k for k in AR if k not in en]
    if missing or extra:
        raise SystemExit(f'missing: {missing}\nextra: {extra}')
    out = {'@@locale': 'ar'}
    for k in keys:
        out[k] = AR[k]
    Path('lib/src/app/l10n/app_ar.arb').write_text(
        json.dumps(out, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n'
    )
    write_review(en, out)
    print(f'wrote {len(keys)} strings')


def write_review(en, ar):
    """docs/arabic-strings-review.md: English and Arabic side by side."""
    def cell(s):
        return s.replace('|', '\\|').replace('\n', ' ')

    lines = [
        '# Arabic strings — review list', '',
        'Generated by `tool/arabic_strings.py`; edit the Arabic there, not here.',
        'Draft Arabic for every string in the app, for review before release.',
        'Numbers show as `{minutes}` etc.; Arabic counting forms',
        '(دقيقة / دقيقتين / ٣ دقائق / ١١ دقيقة) appear as `{minutes, plural, …}`.', '',
        'Terms used throughout: الأذان (Adhan) · الإقامة (Iqama) · تذكير الجماعة',
        '(Jama’ah reminder) · القبلة (Qibla) · وضع السفر (Travel mode) ·',
        'الأذان القصير / الكامل (Short / Full Adhan).', '',
        '| # | Key | English | العربية |', '|---|---|---|---|',
    ]
    n = 0
    for k, v in en.items():
        if k.startswith('@'):
            continue
        n += 1
        lines.append(f'| {n} | `{k}` | {cell(v)} | {cell(ar[k])} |')
    Path('docs/arabic-strings-review.md').write_text(
        '\n'.join(lines) + '\n', encoding='utf-8', newline='\n'
    )


if __name__ == '__main__':
    main()
