# Generates lib/src/app/l10n/arabic_digits_localizations.dart (2026-10-14).
#
#   flutter gen-l10n && python tool/gen_arabic_digits.py
#
# The Arabic UI shows Arabic-Indic digits (٠١٢٣). Numbers reach the strings as
# plain values ("{minutes}"), so instead of formatting each one by hand, this
# writes a subclass of the generated Arabic strings that passes every result
# through arabicDigits(). A test fails if a string is added without rerunning.
import re
from pathlib import Path

SRC = Path('lib/src/app/l10n/generated/app_localizations.dart')
OUT = Path('lib/src/app/l10n/arabic_digits_localizations.dart')

src = SRC.read_text(encoding='utf-8')
getters = re.findall(r'^  String get (\w+);$', src, flags=re.M)
methods = re.findall(r'^  String (\w+)\(([^)]*)\);$', src, flags=re.M)

lines = [
    '// GENERATED by tool/gen_arabic_digits.py. Do not edit by hand.',
    '',
    "import 'digits.dart';",
    "import 'generated/app_localizations_ar.dart';",
    '',
    '/// The Arabic strings with every digit shown as Arabic-Indic (٠١٢٣).',
    'class AppLocalizationsArDigits extends AppLocalizationsAr {',
    "  AppLocalizationsArDigits([super.locale = 'ar']);",
    '',
]
for name in getters:
    lines += ['  @override', f'  String get {name} => arabicDigits(super.{name});', '']
for name, params in methods:
    args = ', '.join(p.strip().split(' ')[-1] for p in params.split(',') if p.strip())
    lines += [
        '  @override',
        f'  String {name}({params}) =>',
        f'      arabicDigits(super.{name}({args}));',
        '',
    ]
lines[-1:] = ['}', '']
OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print(f'{len(getters)} getters, {len(methods)} methods')
